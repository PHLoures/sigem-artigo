function icone(nome, tamanho) {
    const caminho = ICONES[nome];
    if (!caminho) return '';
    const lado = tamanho ? ` width="${tamanho}" height="${tamanho}"` : '';
    return `<svg class="svg-ico"${lado} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${caminho}</svg>`;
}

// Troca todo <span data-ico="nome"></span> pelo SVG correspondente.
// Pode ser chamada de novo quando entrar conteudo novo na pagina.
function hidratarIcones(raiz = document) {
    raiz.querySelectorAll('[data-ico]:not([data-ico-ok])').forEach((el) => {
        el.innerHTML = icone(el.dataset.ico);
        el.setAttribute('data-ico-ok', '1');
    });
}

// Protege contra codigo malicioso digitado em campos de texto.
// Tudo que vem do banco (nome de remedio, motivo, setor...) e passado
// por aqui antes de entrar no HTML: "<" vira "&lt;", etc. Assim um
// nome como <img onerror=...> aparece como texto, sem executar nada.
function esc(valor) {
    return String(valor ?? '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}
